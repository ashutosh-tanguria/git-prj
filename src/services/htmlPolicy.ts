import DOMPurify from "dompurify";
export function htmlPreview(text: string) {
  return DOMPurify.sanitize(text, {
    ALLOWED_TAGS: [
      "h1",
      "h2",
      "h3",
      "h4",
      "h5",
      "h6",
      "p",
      "div",
      "span",
      "br",
      "hr",
      "pre",
      "code",
      "blockquote",
      "ul",
      "ol",
      "li",
      "dl",
      "dt",
      "dd",
      "table",
      "thead",
      "tbody",
      "tr",
      "th",
      "td",
      "strong",
      "em",
      "b",
      "i",
      "u",
      "s",
      "sub",
      "sup",
      "section",
      "article",
      "header",
      "footer",
      "figure",
      "figcaption",
      "a",
    ],
    ALLOWED_ATTR: ["title", "lang", "dir", "colspan", "rowspan"],
    ALLOW_DATA_ATTR: false,
  });
}
